export function createShuffledDeck() {
  const deck = DECK_RECIPE.map(([key, suit, rank], idx) => ({
    uid: `trc-${idx + 1}`,
    key,
    suit,
    rank,
  }));
  for (let i = deck.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }
  return deck;
}
